#!/usr/bin/env bash
# Run this ON THE STEAM DECK, in Desktop Mode (Konsole), once:
#   curl -fsSL https://raw.githubusercontent.com/gabrielvaz/stream-deck-coding-agents/main/steamdeck/install-on-deck.sh | bash -s -- "http://192.168.1.20:7777/#k=TOKEN"
# or copy this folder over and run:  ./install-on-deck.sh "http://192.168.1.20:7777/#k=TOKEN"
#
# It installs Chromium (flatpak) if needed, writes a kiosk launcher, a desktop entry and
# tells you how to add the launcher as a non-Steam game so it shows up in Gaming Mode.
set -euo pipefail

URL="${1:-}"
if [[ -z "$URL" ]]; then
  read -r -p "Deck URL printed by 'agent-deck serve' (e.g. http://192.168.1.20:7777/#k=TOKEN): " URL
fi
if [[ -z "$URL" ]]; then
  echo "A URL is required." >&2
  exit 1
fi

APP_DIR="$HOME/.local/share/agent-deck"
mkdir -p "$APP_DIR" "$HOME/.local/share/applications" "$HOME/.local/share/icons"

BROWSER=""
if command -v flatpak >/dev/null 2>&1; then
  if ! flatpak info org.chromium.Chromium >/dev/null 2>&1; then
    echo "Installing Chromium from Flathub (one-time, ~150 MB)…"
    flatpak install -y --user flathub org.chromium.Chromium || flatpak install -y flathub org.chromium.Chromium
  fi
  BROWSER="flatpak run org.chromium.Chromium"
elif command -v chromium >/dev/null 2>&1; then
  BROWSER="chromium"
elif command -v google-chrome >/dev/null 2>&1; then
  BROWSER="google-chrome"
elif command -v firefox >/dev/null 2>&1; then
  BROWSER="firefox --kiosk"
fi
if [[ -z "$BROWSER" ]]; then
  echo "No browser found. Install Chromium from Discover (flatpak) and run this again." >&2
  exit 1
fi

printf '%s\n' "$URL" > "$APP_DIR/url"

cat > "$APP_DIR/agent-deck.sh" <<LAUNCH
#!/usr/bin/env bash
# Agent Deck kiosk launcher (generated by install-on-deck.sh)
URL="\$(cat "$APP_DIR/url")"
PROFILE="$APP_DIR/profile"
mkdir -p "\$PROFILE"
if [[ "$BROWSER" == firefox* ]]; then
  exec $BROWSER "\$URL"
fi
exec $BROWSER \\
  --kiosk \\
  --user-data-dir="\$PROFILE" \\
  --no-first-run \\
  --disable-session-crashed-bubble \\
  --disable-infobars \\
  --noerrdialogs \\
  --autoplay-policy=no-user-gesture-required \\
  --window-size=1280,800 \\
  --window-position=0,0 \\
  --force-device-scale-factor=1 \\
  "\$URL"
LAUNCH
chmod +x "$APP_DIR/agent-deck.sh"

cp "$(dirname "$0")/icon.svg" "$HOME/.local/share/icons/agent-deck.svg" 2>/dev/null || true

cat > "$HOME/.local/share/applications/agent-deck.desktop" <<DESKTOP
[Desktop Entry]
Type=Application
Name=Agent Deck
Comment=Live status of your coding agents
Exec=$APP_DIR/agent-deck.sh
Icon=agent-deck
Terminal=false
Categories=Development;Utility;
DESKTOP

echo
echo "✔ Launcher: $APP_DIR/agent-deck.sh"
echo "✔ Desktop entry: ~/.local/share/applications/agent-deck.desktop"
echo
echo "Add it to Gaming Mode:"
echo "  1. Still in Desktop Mode, open Steam → Games → Add a Non-Steam Game to My Library…"
echo "  2. Click Browse, choose $APP_DIR/agent-deck.sh (set file type to 'All files'), Add Selected Programs."
echo "  3. Optional: right-click it → Properties → rename to 'Agent Deck', set artwork."
echo "  4. Properties → Controller → choose the 'Keyboard (WASD) and Mouse' template or the plain 'Gamepad' template."
echo "     Both work: the deck reads the gamepad directly and also understands WASD / arrows / Enter / Esc."
echo "  5. Return to Gaming Mode and launch Agent Deck from the Non-Steam tab."
echo
echo "Change the URL later: edit $APP_DIR/url"
